// Regenerates src/theme.css from the brand seed colour: `node scripts/gen-theme.mjs`
import { writeFileSync } from "node:fs";
import { Hct, SchemeTonalSpot, argbFromHex } from "@ktibow/material-color-utilities-nightly";
import { colors, genCSS } from "m3-svelte/etc/colors";

const SEED = "#2f6b4f";
// Default density (0). See the theme page on kendell.dev/m3-svelte for other values.
const DENSITY = `@function --m3-density(--size) {
  result: var(--size);
}`;

const source = Hct.fromInt(argbFromHex(SEED));
const light = new SchemeTonalSpot(source, false, 0, "2025");
const dark = new SchemeTonalSpot(source, true, 0, "2025");

writeFileSync(
  new URL("../src/theme.css", import.meta.url),
  `/* Generated by scripts/gen-theme.mjs (seed ${SEED}). Do not edit by hand. */\n${DENSITY}\n${genCSS(light, dark, colors)}\n`,
);
